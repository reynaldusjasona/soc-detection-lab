#!/usr/bin/env python3
"""Generate a MITRE ATT&CK Navigator layer from the Sigma rules in detections/.

Reads every detections/*.yml, pulls its ATT&CK technique tags (attack.tNNNN[.NNN])
and tactic tags, and writes coverage/attack-navigator-layer.json. The layer is a
build artifact: regenerate it whenever rules change. CI checks it is up to date.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
RULES_DIR = REPO / "detections"
OUT = REPO / "coverage" / "attack-navigator-layer.json"

TECHNIQUE_RE = re.compile(r"^attack\.(t\d{4}(?:\.\d{3})?)$", re.IGNORECASE)
# ATT&CK Enterprise tactic tag -> Navigator tactic shortname
TACTICS = {
    "reconnaissance": "reconnaissance",
    "resource_development": "resource-development",
    "initial_access": "initial-access",
    "execution": "execution",
    "persistence": "persistence",
    "privilege_escalation": "privilege-escalation",
    "defense_evasion": "defense-evasion",
    "credential_access": "credential-access",
    "discovery": "discovery",
    "lateral_movement": "lateral-movement",
    "collection": "collection",
    "command_and_control": "command-and-control",
    "exfiltration": "exfiltration",
    "impact": "impact",
}


def load_rules() -> list[dict]:
    rules = []
    for path in sorted(RULES_DIR.glob("*.yml")):
        with path.open() as fh:
            doc = yaml.safe_load(fh)
        if not isinstance(doc, dict) or "title" not in doc:
            continue
        doc["_file"] = path.name
        rules.append(doc)
    return rules


def build_techniques(rules: list[dict]) -> list[dict]:
    # technique id -> {tactic, rules: [(file, title)]}
    coverage: dict[str, dict] = {}
    for rule in rules:
        tags = [str(t).lower() for t in rule.get("tags", [])]
        techniques = [m.group(1).upper() for t in tags if (m := TECHNIQUE_RE.match(t))]
        tactics = [TACTICS[t.replace("attack.", "")] for t in tags
                   if t.replace("attack.", "") in TACTICS]
        tactic = tactics[0] if tactics else None
        for tech in techniques:
            entry = coverage.setdefault(tech, {"tactic": tactic, "rules": []})
            if tactic and not entry["tactic"]:
                entry["tactic"] = tactic
            entry["rules"].append((rule["_file"], rule.get("title", "")))

    out = []
    for tech, info in sorted(coverage.items()):
        comment = "; ".join(f"{f} ({t})" for f, t in info["rules"])
        entry = {
            "techniqueID": tech,
            "score": len(info["rules"]),
            "color": "",
            "comment": comment,
            "enabled": True,
            "metadata": [],
            "showSubtechniques": "." in tech,
        }
        if info["tactic"]:
            entry["tactic"] = info["tactic"]
        out.append(entry)
    return out


def main() -> int:
    rules = load_rules()
    techniques = build_techniques(rules)
    layer = {
        "name": "soc-detection-lab coverage",
        "versions": {"attack": "15", "navigator": "4.9.5", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": (
            "Techniques detected by the Sigma rules in this repo. Auto-generated by "
            "tools/generate_navigator_layer.py from the rules' ATT&CK tags. Score = "
            "number of rules covering the technique."
        ),
        "sorting": 0,
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {
            "colors": ["#ffe766", "#ff6666"],
            "minValue": 1,
            "maxValue": 3,
        },
        "legendItems": [],
        "showTacticRowBackground": True,
        "tacticRowBackground": "#205b8f",
        "selectTechniquesAcrossTactics": True,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w") as fh:
        json.dump(layer, fh, indent=2)
        fh.write("\n")
    print(f"Wrote {OUT.relative_to(REPO)} with {len(techniques)} techniques "
          f"from {len(rules)} rules.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
